# Generate Iris stub sources for the Google API closure (signatures from javap; bodies are Iris's own defaults).
import json, os, re, sys, collections
M = json.load(open(os.path.expanduser("~/.buildtmp/item9/gen/model.json")))
classes, S = M["classes"], set(M["closure"])
OUT = os.path.expanduser(sys.argv[1])
HDR = ("// Copyright 2026 jegly. Licensed under the GNU General Public License v2.0 or later.\n"
       "// Iris stub (apply-android-gms-stubs.sh): same names and signatures as the Google library API Chromium compiles\n"
       "// against, no Google code. Every call does nothing / reports \"not available\". Generated by\n"
       "// patches/gms-stubs/gen.py from public API signatures.\n")
def src(t): return t.replace("$", ".")
PRIMS = {"boolean": "false", "byte": "(byte) 0", "short": "(short) 0", "char": "(char) 0", "int": "0", "long": "0L",
         "float": "0f", "double": "0d"}
def default_return(rt):
    rt = rt.strip()
    if rt == "void": return ""
    if rt in PRIMS: return "return %s;" % PRIMS[rt]
    base = rt.split("<")[0]
    if base == "com.google.android.gms.tasks.Task": return "return com.google.android.gms.tasks.IrisTasks.failed();"
    return "return null;"
def split_decl(decl):
    # "public abstract class a.b.C<T> extends a.b.D implements a.b.E, a.b.F {"
    m = re.match(r'^(.*?)(class|interface|enum|@interface) (\S+?)(<.*?>)?( extends .*?)?( implements .*?)?\s*\{$', decl)
    return m.groups() if m else None
by_outer = collections.defaultdict(list)
top = []
for c in sorted(S):
    if "$" in c:
        outer = c.rsplit("$", 1)[0]
        if outer in S: by_outer[outer].append(c); continue
    top.append(c)
def simple(c): return c.rsplit("$", 1)[-1] if "$" in c else c.rsplit(".", 1)[-1]
def gen_class(c, indent, nested):
    info = classes[c]; g = split_decl(info["decl"])
    if not g: return indent + "// Iris: could not parse %s\n" % c
    mods, kind, name, tparams, ext, impl = g
    if kind == "interface" and ext and "java.lang.annotation.Annotation" in ext:
        kind = "@interface"; mods = mods.replace("abstract ", "")
    mods = mods.replace("final ", "") if kind == "class" else mods
    if not nested: mods = mods.replace("static ", "").replace("protected ", "public ")
    elif kind == "class" and "static " not in mods: mods = mods + "static "   # javap does not show it; stubs: always static
    nm = simple(c)
    if re.match(r'^\d', nm): return ""   # anonymous
    head = "%s%s%s %s%s" % (indent, mods, kind, nm, src(tparams or ""))
    if kind == "enum": ext = None
    if kind == "@interface": ext = None; impl = None
    if ext: head += src(ext)
    if impl: head += src(impl)
    out = [head + " {"]
    ind = indent + "  "
    members = info["members"]
    if kind == "enum":
        consts = [re.match(r'public static final \S+ (\w+);', m).group(1) for m in members
                  if re.match(r'public static final %s (\w+);' % re.escape(c), m)]
        out.append(ind + (", ".join(consts) or "IRIS_NONE") + ";")
    has_noarg = False; ctor_any = False
    seen = set()
    for m in members:
        m = m.rstrip(";")
        if kind == "enum" and (re.match(r'public static final %s \w+$' % re.escape(c), m) or " values()" in m or " valueOf(java.lang.String)" in m):
            continue
        if m.startswith("static {}") or m.startswith("{}"): continue
        if "kotlinx.coroutines." in m: continue   # Iris: coroutines are not visible outside android_deps; Chromium's Java does not use these
        msrc = src(m)
        # field?
        if "(" not in m:
            if " = " in msrc or kind in ("interface", "@interface"):
                fld = msrc if " = " in msrc else None
                if fld is None:
                    t = msrc.split()[-2]
                    fld = msrc + " = " + (PRIMS.get(t, "null"))
                out.append(ind + fld + ";")
            else:
                if " final " in " " + msrc + " ":
                    t = msrc.split()[-2]
                    out.append(ind + msrc + " = " + PRIMS.get(t, "null") + ";")
                else:
                    out.append(ind + msrc + ";")
            continue
        # method / constructor
        sig = re.sub(r'\s+throws .*$', '', msrc)
        key = re.sub(r'<[^<>]*>', '', re.sub(r'<[^<>]*>', '', sig))
        key = re.sub(r'^.*?(\w+\(.*\))$', r'\1', key)
        if key in seen: continue
        seen.add(key)
        # bridge methods: an all-Object twin of a generic method with the same name and arity
        bm = re.match(r'^(\w+)\((.*)\)$', key)
        if bm and bm.group(2) and all(x.strip() == "java.lang.Object" for x in bm.group(2).split(",")):
            arity = len(bm.group(2).split(","))
            if any(re.match(r'^.*\s%s\(' % re.escape(bm.group(1)), src(o)) and src(o).count(",") + 1 == arity
                   and "java.lang.Object" not in src(o).split("(", 1)[1] for o in members):
                continue
        # parameter names
        pm = re.match(r'^(.*)\((.*)\)(.*)$', msrc)
        pre, params, post = pm.groups()
        plist = []
        if params.strip():
            depth = 0; cur = ""
            for ch in params:
                if ch == "<": depth += 1
                if ch == ">": depth -= 1
                if ch == "," and depth == 0: plist.append(cur.strip()); cur = ""
                else: cur += ch
            plist.append(cur.strip())
        named = ", ".join("%s p%d" % (t, i) for i, t in enumerate(plist))
        is_ctor = re.search(r'(^|\s)' + re.escape(src(c)) + r'$', pre.strip()) is not None
        if is_ctor:
            ctor_any = True
            if not plist: has_noarg = True
            pre = re.sub(re.escape(src(c)) + r'$', nm, pre.strip())
            out.append(ind + "%s(%s)%s { %s}" % (pre, named, post, "super(); " if False else ""))
            continue
        decl = "%s(%s)%s" % (pre, named, post)
        if kind == "@interface":
            out.append(ind + re.sub(r'^public abstract ', '', decl) + ";"); continue
        if kind == "interface" and " default " not in " " + pre + " " and " static " not in " " + pre + " ":
            out.append(ind + decl + ";"); continue
        if " abstract " in " " + pre + " " or " native " in " " + pre + " ":
            out.append(ind + decl + ";"); continue
        rt = re.sub(r'^.*?\s((?:[\w.$]+(?:<.*>)?(?:\[\])*))\s+\w+$', r'\1', pre.strip())
        rt = rt.replace("[]", "") if False else rt
        body = default_return(rt) if not rt.endswith("[]") else "return null;"
        mname = re.search(r'(\w+)$', pre.strip()).group(1)
        if mname == "isGooglePlayServicesAvailable" and rt == "int":
            body = "return 1; /* Iris: ConnectionResult.SERVICE_MISSING */"
        out.append(ind + "%s { %s }" % (decl, body))
    if kind == "class" and not has_noarg:
        out.append(ind + "protected %s() {}  // Iris" % nm)
    for n in by_outer.get(c, []):
        out.append(gen_class(n, ind, True))
    out.append(indent + "}")
    return "\n".join(out) + "\n"
n = 0
for c in top:
    pkg, nm = c.rsplit(".", 1)
    path = os.path.join(OUT, pkg.replace(".", "/"), nm + ".java")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    body = gen_class(c, "", False)
    # fix-ups javap cannot express
    for a, b in (("= -Infinityd", "= Double.NEGATIVE_INFINITY"), ("= Infinityd", "= Double.POSITIVE_INFINITY"),
                 ("= NaNd", "= Double.NaN"), ("= -Infinityf", "= Float.NEGATIVE_INFINITY"),
                 ("= Infinityf", "= Float.POSITIVE_INFINITY"), ("= NaNf", "= Float.NaN")):
        body = body.replace(a, b)
    if c == "com.google.android.gms.common.api.internal.BaseImplementation":
        body = body.replace("    public void setResult(java.lang.Object p0) {  }\n", "")  # inherited final from BasePendingResult
    open(path, "w").write(HDR + "\npackage %s;\n\n" % pkg + body)
    n += 1
print("wrote", n, "files")
