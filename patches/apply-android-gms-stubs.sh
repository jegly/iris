#!/usr/bin/env bash
# Iris — Android: no Google Play services, Firebase, Play Core or ML Kit code in the APK (issue #1 item 9, jegly
# 2026-11-05: "do it now"). Before: Iris never USED them (apply-android-no-gms.sh makes every check say "not
# available"), but Chromium's build still put 34 Google client libraries (+ ML Kit) into the APK as dead code.
# Now: build/config/android/config.gni's google_play_services_package (Chromium's hook for a different Play services
# package; a plain variable, not a gn arg) is set to "//third_party/iris_gms_stubs", so every "$google_play_services_package:<lib>" dependency
# resolves to Iris's stub library (patches/src/third_party/iris_gms_stubs, copied here). The stubs have the same class
# names and signatures as the API Chromium's code compiles against (generated by patches/gms-stubs/gen.py from the
# public signatures; no Google code), and every call does nothing or reports "not available":
#   - isGooglePlayServicesAvailable() -> ConnectionResult.SERVICE_MISSING; Task-returning calls -> an already-failed
#     Task (IrisTasks: failure/complete listeners run at once, success never); everything else false/0/null.
# Play Core (feature delivery, in-app update, in-app review) and ML Kit (on-device Gemini through AICore) are not
# behind that arg: overrides.gni's playcore_java / playcore_app_update_java / mlkit_java groups and the 3 direct
# in-app-review dependencies point at the stubs here.
# Passkeys / security keys are unaffected: Iris uses Android's Credential Manager (apply-android-webauthn-credman.sh),
# not the Play services FIDO path the stubs replace.
# Proof after a build: no com/google/android/gms|firebase|android/play|mlkit classes except the stubs
#   (they are tiny: every method body is a default return).
# Rebase: if Chromium starts using a new Google class/method, chrome_java fails to compile -> regenerate the stubs
#   (patches/gms-stubs/README in the header of gen.py) and re-run this script.
# STATUS 2026-11-05: the 58 Chromium files that use Google classes compile against the stubs (standalone javac,
#   0 errors); NOT yet built through gn/siso (APK, R8, manifest merge).
# Guarded; idempotent; fails loudly on drift.
set -euo pipefail
SRC="${1:-$HOME/Documents/chromium/src}"
PSRC="$(cd "$(dirname "$0")" && pwd)/src"
cd "$SRC"
D=third_party/iris_gms_stubs
[ -f "$PSRC/$D/BUILD.gn" ] || { echo "ERROR: $PSRC/$D missing" >&2; exit 1; }
# mirror the stub package exactly (stale generated files from an older run are removed)
mkdir -p "$D"
changed=0
while IFS= read -r -d '' f; do
  rel="${f#"$PSRC/"}"
  mkdir -p "$(dirname "$rel")"
  if ! cmp -s "$f" "$rel"; then cp "$f" "$rel"; changed=$((changed + 1)); fi
done < <(find "$PSRC/$D" -type f -print0)
while IFS= read -r -d '' f; do
  [ -f "$PSRC/$f" ] || { rm "$f"; changed=$((changed + 1)); }
done < <(find "$D" -type f -print0)
[ "$changed" -eq 0 ] && echo "SKIP up to date: $D" || echo "OK   $D : $changed file(s) copied/removed"
python3 - <<'PY'
import sys
def die(m): sys.stderr.write("ERROR: " + m + "\n"); sys.exit(1)
def edit(p, old, new, marker, label):
    s = open(p).read()
    if marker in s: print("SKIP already applied: %s (%s)" % (p, label)); return
    if s.count(old) != 1: die("%s: anchor for %s not found exactly once (drift?)" % (p, label))
    open(p, "w").write(s.replace(old, new, 1)); print("OK   %s : %s" % (p, label))
STUBS = '"//third_party/iris_gms_stubs:iris_gms_stubs_java"'
O = "third_party/android_deps/overrides.gni"
edit(O, '        deps = [ "//third_party/android_deps:com_google_android_play_feature_delivery_java" ]\n',
     '        deps = [ %s ]  # Iris: no Play Core (apply-android-gms-stubs.sh)\n' % STUBS,
     "no Play Core (apply-android-gms-stubs.sh)", "Play Core feature delivery")
edit(O, '        deps = [\n          "//third_party/android_deps:com_google_android_play_app_update_java",\n        ]\n',
     '        deps = [ %s ]  # Iris: no Play in-app update\n' % STUBS,
     "# Iris: no Play in-app update", "Play in-app update")
edit(O, '        deps = [\n'
        '          ":com_google_mlkit_common_java",\n'
        '          ":com_google_mlkit_genai_common_java",\n'
        '          ":com_google_mlkit_genai_prompt_java",\n'
        '        ]\n',
     '        deps = [ %s ]  # Iris: no ML Kit\n' % STUBS,
     "# Iris: no ML Kit", "ML Kit")
# google_play_services_package is NOT a gn arg (an args.gn value is ignored: "Build argument has no effect"); its
# default lives inside the is_android block of build/config/android/config.gni -> set it there.
edit("build/config/android/config.gni",
     '    google_play_services_package = "//third_party/android_deps"\n',
     '    # Iris: Play services + Firebase come from Iris\'s stubs (apply-android-gms-stubs.sh).\n'
     '    google_play_services_package = "//third_party/iris_gms_stubs"\n',
     'google_play_services_package = "//third_party/iris_gms_stubs"', "Play services package -> Iris stubs")
R = '"//third_party/android_deps:com_google_android_play_review_java"'
edit("chrome/android/BUILD.gn", "          [ %s ]\n" % R,
     "          [ %s ]  # Iris: no Play in-app review\n" % STUBS,
     "# Iris: no Play in-app review", "in-app review (chrome)")
A = "chrome/browser/ui/android/app_rating/BUILD.gn"
s = open(A).read()
old = "    deps += [ %s ]\n" % R
if "# Iris: no Play in-app review" in s:
    print("SKIP already applied: %s (in-app review)" % A)
elif s.count(old) != 2:
    die("%s: expected 2 in-app review deps, found %d (drift?)" % (A, s.count(old)))
else:
    open(A, "w").write(s.replace(old, "    deps += [ %s ]  # Iris: no Play in-app review\n" % STUBS))
    print("OK   %s : in-app review (java + junit)" % A)
PY
echo "=== Android Google libraries -> Iris stubs complete ==="
